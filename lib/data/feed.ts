/** ISO timestamp offset from now so seeded content always reads as current. */
function at(dayOffset: number, hour = 9, minute = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

