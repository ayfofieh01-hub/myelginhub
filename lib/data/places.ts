import type { LiveWellSlug, Place, TownId } from '@/lib/types';

let phoneSeed = 4100;

type Extra = {
  sub?: string;
  hours?: string;
  rating?: number;
  tags?: string[];
  liveWell?: LiveWellSlug;
  directory?: string;
};

function p(
  town: TownId,
  category: string,
  name: string,
  blurb: string,
  address: string,
  extra: Extra = {},
): Place {
  phoneSeed += 7;
  const area = town === 'aylmer' ? '773' : town === 'port-stanley' ? '782' : '631';
  return {
    id: `${town}-${category}-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`,
    town,
    name,
    category,
    subCategory: extra.sub,
    blurb,
    address,
    phone: `(519) ${area}-${phoneSeed}`,
    hours: extra.hours ?? 'Mon–Fri 9:00–17:00',
    rating: extra.rating ?? 4.4,
    tags: extra.tags ?? [],
    liveWell: extra.liveWell,
    directory: extra.directory,
  };
}

